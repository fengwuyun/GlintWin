using GlintWin;
using System.Diagnostics;
var path = args[0];
GC.Collect(); GC.WaitForPendingFinalizers(); GC.Collect();
long before = GC.GetTotalAllocatedBytes(true);
var timer = Stopwatch.StartNew();
var dictionary = CedictDictionary.Load(path) ?? throw new Exception("Load failed");
timer.Stop();
long allocated = GC.GetTotalAllocatedBytes(true) - before;
long live = GC.GetTotalMemory(true);
var proc = Process.GetCurrentProcess();
Console.WriteLine($"entries={dictionary.Count}; allocatedMB={allocated/1048576d:F2}; retainedMB={live/1048576d:F2}; elapsedMs={timer.ElapsedMilliseconds}; privateMB={proc.PrivateMemorySize64/1048576d:F2}");
foreach(var word in new[]{"学习","不对","你好","中国","人工智能"}) Console.WriteLine(word+"="+dictionary.Lookup(word));
GC.KeepAlive(dictionary);
var mapField = typeof(CedictDictionary).GetField("_map", System.Reflection.BindingFlags.NonPublic | System.Reflection.BindingFlags.Instance)!;
var keys = ((System.Collections.IDictionary)mapField.GetValue(dictionary)!).Keys.Cast<string>().OrderBy(x => x, StringComparer.Ordinal);
using var hash = System.Security.Cryptography.IncrementalHash.CreateHash(System.Security.Cryptography.HashAlgorithmName.SHA256);
foreach (var word in keys) hash.AppendData(System.Text.Encoding.UTF8.GetBytes(word + "\t" + dictionary.PinyinOf(word) + "\t" + dictionary.Lookup(word) + "\n"));
Console.WriteLine("FullDictionarySHA256=" + Convert.ToHexString(hash.GetHashAndReset()));
